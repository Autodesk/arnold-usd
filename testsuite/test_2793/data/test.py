import os
import subprocess
import sys

# When the procedural under test is the ArnoldUsdBundle, remove its folder from
# PXR_PLUGINPATH_NAME, so that the render only works if the bundle registers its
# own plugInfo files (#2793). With other builds the environment is left as is.
env = dict(os.environ)

def is_bundle_folder(folder):
    return os.path.isdir(folder) and any(f.startswith('ArnoldUsdBundle.') for f in os.listdir(folder))

bundle_folders = set(os.path.realpath(p) for p in env.get('ARNOLD_PLUGIN_PATH', '').split(os.pathsep)
                     if p and is_bundle_folder(p))
if bundle_folders:
    plugin_paths = [p for p in env.get('PXR_PLUGINPATH_NAME', '').split(os.pathsep)
                    if p and os.path.realpath(p) not in bundle_folders]
    env['PXR_PLUGINPATH_NAME'] = os.pathsep.join(plugin_paths)
    print('Removed the bundle from PXR_PLUGINPATH_NAME: {}'.format(env['PXR_PLUGINPATH_NAME']))
else:
    print('The procedural is not the ArnoldUsdBundle, leaving PXR_PLUGINPATH_NAME unchanged')
sys.stdout.flush()

# Same command line as the one generated by the testsuite for a scene
cmd = ['kick', 'scene.usda', '-dw', '-r', '160', '120', '-bs', '16', '-sm', 'lambert', '-sl',
       '-o', 'testrender.tif', '-set', 'driver_tiff.dither', 'false', '-dp']
if sys.platform == 'win32':
    cmd.append('-nocrashpopup')

result = subprocess.run(cmd, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, universal_newlines=True)
print(result.stdout)

if result.returncode != 0:
    sys.exit(result.returncode)
if 'Could not create the HdArnoldRendererPlugin render delegate' in result.stdout:
    sys.exit(-1)
if not os.path.exists('testrender.tif'):
    sys.exit(-1)
